def _index(path):
    return int(re.search(r'cfg_(\d+)\.in$', path).group(1))


def run_local(inputs):
    """pw.x on every input, one after the other; a failed configuration is skipped (the 95 % rule)."""
    for path in inputs:
        folder, name = os.path.split(path)
        stem = name[:-3]
        print('  running %s' % os.path.relpath(path, HERE), flush=True)
        subprocess.run('%s %s -in %s.in > %s.out 2>&1' % (MPI_QE, QE_PW, stem, stem), shell=True, cwd=folder)
        for scratch in glob.glob(os.path.join(folder, 'tmp_*_%04d' % _index(path))):
            shutil.rmtree(scratch, ignore_errors=True)


def _array_spec(indices):
    """Slurm array specification of a list of indices ('0-99', '3,7-9')."""
    indices, parts, start = sorted(indices), [], None
    for i, value in enumerate(indices):
        start = value if start is None else start
        if i == len(indices) - 1 or indices[i + 1] != value + 1:
            parts.append(str(start) if start == value else '%d-%d' % (start, value))
            start = None
    return ','.join(parts)


def _sbatch(directives, body, name, log, script, extra=()):
    """Write and submit a batch script; return the job id."""
    with open(script, 'w') as handle:
        handle.write('\n'.join(['#!/bin/bash'] + list(directives) + list(ENV_SETUP) + list(body)) + '\n')
    out = subprocess.run(['sbatch', '--parsable', '-J', name, '-o', log, *extra, script],
                         capture_output=True, text=True, check=True).stdout
    return re.findall(r'^(\d+)', out, re.M)[-1]


def _submit_step(temperature, folder, dependency=None):
    """The step job of one temperature (after the array ``dependency``, if given)."""
    logs = os.path.join(sscha_dir(temperature), 'logs')
    os.makedirs(logs, exist_ok=True)
    extra = ['--dependency=afterany:%s' % dependency] if dependency else []
    body = ['cd %s' % HERE, '%s %s step --temperature %g --chain' % (PYTHON, os.path.abspath(__file__), temperature)]
    return _sbatch(SLURM_STEP_DIRECTIVES, body, 'sscha_T%g_step' % temperature, os.path.join(logs, '%x.%j.out'),
                   os.path.join(folder, 'step.sh'), extra)


def submit_slurm(temperature, inputs):
    """Job array of the missing configurations and the step job that follows it (afterany)."""
    folder = os.path.dirname(inputs[0])
    logs = os.path.join(sscha_dir(temperature), 'logs')
    os.makedirs(logs, exist_ok=True)
    body = ['cd %s' % folder, 'idx=$(printf %04d "$SLURM_ARRAY_TASK_ID")',
            '%s %s -in cfg_$idx.in > cfg_$idx.out 2>&1' % (MPI_QE, QE_PW), 'rm -rf tmp_*_$idx']
    array = _sbatch(SLURM_DIRECTIVES, body, 'sscha_T%g_%s' % (temperature, os.path.basename(folder)),
                    os.path.join(logs, '%x.%A_%a.out'), os.path.join(folder, 'pw_array.sh'),
                    ['--array=%s%%%d' % (_array_spec(_index(p) for p in inputs), SLURM_CONCURRENT)])
    step = _submit_step(temperature, folder, dependency=array)
    print('  submitted %d configurations (array %s) and the step job %s' % (len(inputs), array, step))


def launch(temperature, status):
    """Run or submit the missing configurations of the pending population."""
    if LAUNCHER == 'local':
        run_local(status['missing'])
    elif LAUNCHER == 'slurm':
        submit_slurm(temperature, status['missing'])
    elif LAUNCHER == 'manual':
        print('  run pw.x on these %d inputs (output cfg_XXXX.out next to each), then `run` again:' % len(
            status['missing']))
        for path in status['missing']:
            print('    %s' % os.path.relpath(path, HERE))
    else:
        raise SystemExit("LAUNCHER must be 'local', 'slurm' or 'manual', got %r" % LAUNCHER)


