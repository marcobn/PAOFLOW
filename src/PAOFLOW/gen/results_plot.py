"""Plot scripts drawn from the Results layer (``plot.sscha.py``, ``plot.pyskeaf.py``).

GPAO has no figure of these results; :mod:`PAOFLOW.results` reads them for the Results tab of
``paoflow-studio`` and renders the same figures with matplotlib
(:func:`PAOFLOW.results.export.matplotlib_figure`).  The script saves one file per dataset, so it
needs no display and the Runs tab can run it.
"""

from __future__ import annotations


def build_results_plot_script(
    title: str, driver: str, kinds: tuple[str, ...], outputdir: str
) -> str:
    """Text of a plot script that saves the figures of some result kinds of a folder.

    Parameters
    ----------
    title : str
        What the results are (``'quantum oscillations (pyskeaf)'``).
    driver : str
        The script that writes them (``main.pyskeaf.py``), for the docstring.
    kinds : tuple of str
        Kinds of :data:`PAOFLOW.results.catalogue.KINDS` to draw (``('dhva',)``).
    outputdir : str
        Folder of the results, relative to the script.

    Returns
    -------
    str
    """
    return '\n'.join(
        [
            '#!/usr/bin/env python3',
            '"""Figures of the %s results (generated by paoflow-gen).' % title,
            '',
            'Run after %s.  The figures are those of the Results tab of paoflow-studio' % driver,
            '(PAOFLOW.results), saved in FIGURES, one file per dataset:',
            '',
            '    python %s' % driver.replace('main.', 'plot.', 1),
            '"""',
            '',
            'import os',
            'import re',
            '',
            'from PAOFLOW.results import ResultsFolder',
            'from PAOFLOW.results.export import matplotlib_figure',
            '',
            'HERE = os.path.dirname(os.path.abspath(__file__))',
            'OUTPUTDIR = os.path.join(HERE, %r)' % outputdir,
            "FIGURES = os.path.join(OUTPUTDIR, 'figures')",
            'KINDS = %r   # result kinds drawn (PAOFLOW.results.catalogue)' % (tuple(kinds),),
            "FORMAT = 'pdf'   # pdf, png or svg",
            '',
            '',
            'def main():',
            '    folder = ResultsFolder(OUTPUTDIR)',
            '    references = [ref for ref in folder.datasets if ref.kind in KINDS]',
            '    if not references:',
            "        print('No results to draw in %s yet.' % OUTPUTDIR)",
            '        return',
            '    os.makedirs(FIGURES, exist_ok=True)',
            '    for ref in references:',
            '        try:',
            '            figure = matplotlib_figure(folder.load(ref.id), FORMAT)',
            '        except ValueError as exc:  # a dataset without a 2D figure',
            "            print('skipped %s: %s' % (ref.title, exc))",
            '            continue',
            '        # The path inside OUTPUTDIR names the figure (sscha_T300/state -> sscha_T300_state).',
            "        stem = re.sub(r'\\W+', '_', os.path.splitext(ref.files[0])[0]).strip('_')",
            "        path = os.path.join(FIGURES, '%s.%s' % (stem, FORMAT))",
            "        with open(path, 'wb') as handle:",
            '            handle.write(figure)',
            "        print('wrote', path)",
            '',
            '',
            'if __name__ == "__main__":',
            '    main()',
            '',
        ]
    )
