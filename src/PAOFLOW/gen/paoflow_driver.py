        lines.append("    p.pao_eigh()")
        lines.append("")
        lines.append("    # Non-local velocity is essential for the optical matrix elements.")
        lines.append("    p.gradient_and_momenta(nonlocal_velocity=True)")
        lines.append("    p.adaptive_smearing()")
