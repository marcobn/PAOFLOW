"""``main.ep_model.py`` of an electron-phonon run on a model crystal (workflow ``ep_model``).

The configuration comes from :data:`PAOFLOW.gen.questions.ep_model.EP_MODEL` (``paoflow-gen``,
workflow ``ep_model``, or the Setup tab of ``paoflow-studio``).  The script builds the crystal
with its function of :mod:`PAOFLOW.models.electron_phonon` and calls one step of
:mod:`PAOFLOW.models.electron_phonon.workflows` per property; the outputs have the formats of
the ab initio electron-phonon workflows, so the Results tab reads them.
"""

from __future__ import annotations

from typing import Any

#: Result kinds of :mod:`PAOFLOW.results.catalogue` drawn by ``plot.ep_model.py``.
PLOT_KINDS = (
    'bands',
    'phonon_bands',
    'phonon_dos',
    'alpha2f',
    'gap_vs_t',
    'max_eigenvalue',
    'resistivity',
    'eliashberg_self_energy',
    'mobility',
    'scattering_rates',
    'phonon_assisted_absorption',
    'indirect_eps2',
)


def _literal(value: Any) -> str:
    """Python text of a model argument (floats as floats, the rest as ``repr``)."""
    if isinstance(value, float):
        return repr(float(value))
    return repr(value)


def _floats(values) -> str:
    return '[%s]' % ', '.join(repr(float(v)) for v in values)


def build_ep_model_script(cfg: dict) -> str:
    """Text of the ``main.ep_model.py`` of a model run.

    Parameters
    ----------
    cfg : dict
        :func:`PAOFLOW.gen.questions.ep_model.assemble_ep_model`.

    Returns
    -------
    str
        A serial driver: the editable constants, then ``main()`` with one call of
        :mod:`PAOFLOW.models.electron_phonon.workflows` per property.
    """
    props = list(cfg['properties'])
    function = cfg['model_function']
    arguments = cfg.get('model_arguments', {})
    lines = [
        '#!/usr/bin/env python3',
        '"""Electron-phonon run on the model crystal %s (generated by paoflow-gen).'
        % cfg['ep_model'],
        '',
        'The crystal is PAOFLOW.models.electron_phonon.%s with MODEL_PARAMETERS:' % function,
        'tight-binding electrons whose hoppings depend on the bond length, springs between the same',
        'atoms, and the vertex dH/du of the same model; no DFT run.  The steps are those of',
        'PAOFLOW.models.electron_phonon.workflows, with the output files of the ab initio',
        'electron-phonon workflows (the Results tab of paoflow-studio reads them).  Serial, one core:',
        '',
        '    python main.ep_model.py',
        '"""',
        '',
        'import os',
        '',
        'from PAOFLOW.models.electron_phonon import %s, workflows' % function,
        '',
        '# ----------------------------------------------------------------------- #',
        '# Configuration  (edit freely)                                            #',
        '# ----------------------------------------------------------------------- #',
        'HERE = os.path.dirname(os.path.abspath(__file__))',
        'OUTPUTDIR = os.path.join(HERE, %r)' % cfg['outputdir'],
        '',
        '# The crystal: the arguments of %s' % function,
        '# (help(%s) gives their meaning and units).' % function,
        'MODEL_PARAMETERS = dict(',
    ]
    lines += ['    %s=%s,' % (key, _literal(value)) for key, value in arguments.items()]
    lines += [')', '']
    if 'band_path' in cfg:
        lines += [
            '# Band path of the electrons and the phonons (crystal coordinates of the reciprocal',
            '# vectors of the model; gG is Gamma) and its number of points.',
            'NK_PATH = %d' % int(cfg['nk']),
            'BAND_PATH = %r' % cfg['band_path'],
            'HIGH_SYM = {',
        ]
        lines += [
            '    %r: (%s),' % (label, ', '.join(repr(float(v)) for v in point))
            for label, point in cfg['high_sym'].items()
        ]
        lines += ['}', '']
    if 'superconductivity' in props:
        lines += [
            '# Electron-phonon coupling of the metal: k- and q-points per periodic direction (NQ divides',
            '# NK; the q-grid is folded to its irreducible wedge in 3D), the prefactor of the adaptive',
            '# widths a |v| dk (0: the fixed width SIGMA_EV), the Gaussian width or floor (eV), mu*.',
            'NK, NQ = %d, %d' % (int(cfg['ep_nk']), int(cfg['ep_nq'])),
            'ADAPTIVE_SMEARING = %r' % float(cfg['adaptive_smearing']),
            'SIGMA_EV = %r' % float(cfg['sigma_ev']),
            'MU_STAR = %r' % float(cfg['mu_star']),
        ]
        if 'migdal_eliashberg' in props:
            temps = cfg.get('me_temperatures')
            lines.append(
                'ME_TEMPERATURES = %s   # K; None: from 1 K to 1.6 Tc of Allen-Dynes'
                % (_floats(temps) if temps else 'None')
            )
        if 'resistivity' in props:
            lines.append('RHO_TEMPERATURES = %s   # K' % _floats(cfg['rho_temperatures']))
        if 'self_energy' in props:
            lines.append('SE_TEMPERATURES = %s   # K' % _floats(cfg['se_temperatures']))
        lines.append('')
    if 'mobility' in props:
        lines += [
            '# Mobility of the semiconductor: k-points (= q-points) per periodic direction, carriers',
            "# ('electrons', 'holes' or 'both'), temperatures (K), net doping n_e - n_h (cm^-3).",
            'MOBILITY_NK = %d' % int(cfg['mobility_nk']),
            'MOBILITY_CARRIERS = %r' % cfg['mobility_carriers'],
            'MOBILITY_TEMPERATURES = %s' % _floats(cfg['mobility_temperatures']),
            'DOPING_CM3 = %r' % float(cfg['doping_cm3']),
            '',
        ]
    if 'absorption' in props:
        lines += [
            '# Phonon-assisted absorption: k-points (= q-points) per periodic direction, temperatures',
            '# (K) and the refractive index of the absorption coefficient.',
            'ABSORPTION_NK = %d' % int(cfg['absorption_nk']),
            'ABSORPTION_TEMPERATURES = %s' % _floats(cfg['absorption_temperatures']),
            'REFRACTIVE_INDEX = %r' % float(cfg['refractive_index']),
            '',
        ]
    path = (
        '        model, OUTPUTDIR, band_path=BAND_PATH, high_symmetry_points=HIGH_SYM, nk=NK_PATH'
    )
    calls = {
        'bands': ['    workflows.band_structure(', path, '    )'],
        'phonons': ['    workflows.phonon_dispersion(', path, '    )'],
        'superconductivity': [
            '    workflows.superconductivity(',
            '        model,',
            '        OUTPUTDIR,',
            '        nk=NK,',
            '        nq=NQ,',
            '        sigma_ev=SIGMA_EV,',
            '        adaptive_smearing=ADAPTIVE_SMEARING,',
            '        mu_star=MU_STAR,',
            '    )',
        ],
        'migdal_eliashberg': [
            '    workflows.migdal_eliashberg(OUTPUTDIR, temperatures=ME_TEMPERATURES, mu_star=MU_STAR)'
        ],
        'resistivity': ['    workflows.resistivity(OUTPUTDIR, temperatures=RHO_TEMPERATURES)'],
        'self_energy': ['    workflows.self_energy(OUTPUTDIR, temperatures=SE_TEMPERATURES)'],
        'mobility': [
            '    workflows.mobility(',
            '        model,',
            '        OUTPUTDIR,',
            '        nk=MOBILITY_NK,',
            '        temperatures=MOBILITY_TEMPERATURES,',
            '        carriers=MOBILITY_CARRIERS,',
            '        doping_cm3=DOPING_CM3,',
            '    )',
        ],
        'absorption': [
            '    workflows.phonon_assisted_absorption(',
            '        model,',
            '        OUTPUTDIR,',
            '        nk=ABSORPTION_NK,',
            '        temperatures=ABSORPTION_TEMPERATURES,',
            '        refractive_index=REFRACTIVE_INDEX,',
            '    )',
        ],
    }
    order = (
        'bands',
        'phonons',
        'superconductivity',
        'migdal_eliashberg',
        'resistivity',
        'self_energy',
        'mobility',
        'absorption',
    )
    lines += [
        '',
        'def main():',
        '    model = %s(**MODEL_PARAMETERS)' % function,
    ]
    for name in order:
        if name in props:
            lines += calls[name]
    lines += [
        '',
        '',
        'if __name__ == "__main__":',
        '    main()',
        '',
    ]
    return '\n'.join(lines)
