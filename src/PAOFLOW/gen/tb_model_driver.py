"""``main.py`` of a property run on a tight-binding model (workflow ``tb_model``).

The configuration comes from :data:`PAOFLOW.gen.questions.tb_model.TB_MODEL` (``paoflow-gen``,
workflow ``tb_model``, or the Setup tab of ``paoflow-studio``).  The script builds the model with
its function of :mod:`PAOFLOW.models.models` and runs the properties of the QE property run on it
(:func:`PAOFLOW.gen.paoflow_driver.build_run_script` shares the property calls), with no QE save,
projection or basis.
"""

from __future__ import annotations

from typing import Any


def _literal(value: Any) -> str:
    """Python text of a model argument (floats as floats, the rest as ``repr``)."""
    if isinstance(value, bool) or value is None:
        return repr(value)
    if isinstance(value, float):
        return repr(float(value))
    return repr(value)


def build_tb_model_script(cfg: dict) -> str:
    """Text of the ``main.py`` of a model run.

    Parameters
    ----------
    cfg : dict
        :func:`PAOFLOW.gen.questions.tb_model.assemble_tb_model`.

    Returns
    -------
    str
        A driver with ``run_properties()``, ``run_optical()`` and ``run_nonlinear()`` as the
        properties ask, each on its own PAOFLOW instance of the model.
    """
    from .paoflow_driver import (
        ENERGY_RANGE_BLOCK,
        ENERGY_WINDOW_PROPERTIES,
        SPIN_PROPERTIES,
        _band_path_constant_lines,
        _emit_standard_properties,
        _nonlinear_call_lines,
        _nonlinear_constant_lines,
    )

    props = list(cfg['properties'])
    standard = [p for p in props if p not in ('optical', 'nonlinear')]
    function = cfg['model_function']
    periodic = tuple(cfg.get('periodic', (True, True, True)))
    nfft = tuple(int(cfg['nfft']) if p else 1 for p in periodic)
    arguments = cfg.get('model_arguments', {})
    lines = [
        '#!/usr/bin/env python3',
        '"""PAOFLOW property run on the tight-binding model %s (generated by paoflow-gen).'
        % cfg['tb_model'],
        '',
        'The Hamiltonian is PAOFLOW.models.models.%s with MODEL_PARAMETERS: no DFT run, no'
        % function,
        'projection and no basis.  Edit the constants and the property calls below.  Run with:',
        '',
        '    python main.py',
        '    mpirun -np <N> python main.py',
        '"""',
        '',
        'import os',
        '',
        'from PAOFLOW import PAOFLOW',
        'from PAOFLOW.models.models import %s' % function,
        '',
        'try:',
        '    from mpi4py import MPI',
        '',
        '    RANK = MPI.COMM_WORLD.Get_rank()',
        'except ImportError:',
        '    RANK = 0',
        '',
        '# ----------------------------------------------------------------------- #',
        '# Configuration  (edit freely)                                            #',
        '# ----------------------------------------------------------------------- #',
        'HERE = os.path.dirname(os.path.abspath(__file__))',
        'OUTPUTDIR = %r' % cfg['outputdir'],
        '',
        '# The model: the arguments of %s (help(%s) gives their meaning and units).'
        % (function, function),
        'MODEL_PARAMETERS = dict(',
    ]
    lines += ['    %s=%s,' % (key, _literal(value)) for key, value in arguments.items()]
    lines += [
        ')',
        '',
        'NPOOL = %d' % int(cfg['npool']),
        'SMEARING = %r' % cfg['smearing'],
        '',
        'IBRAV = 0   # the band path is explicit (the lattice of the model)',
        'NK = %d   # k-points along the band path' % int(cfg['nk']),
    ]
    lines += _band_path_constant_lines(cfg)
    lines += [
        '',
        '# Energy grid for DOS / transport / Hall properties (eV; the model sets its own zero).',
        'EMIN, EMAX, NE = %s, %s, %s' % (cfg['emin'], cfg['emax'], cfg['ne']),
    ]
    if 'dos' in props:
        lines.append('DO_PDOS = %s   # projected on the orbitals of the model' % cfg['do_pdos'])
    if 'transport' in props:
        lines.append('TMIN, TMAX, NT = 300.0, 300.0, 1   # temperature grid (K) for transport')
    lines += [
        '',
        '# Dense k-grid of the interpolated Hamiltonian (1 along the directions without hoppings).',
        'NFFT = (%d, %d, %d)' % nfft,
        '',
    ]
    if 'optical' in props:
        span = float(cfg['emax']) - float(cfg['emin'])
        lines += [
            '# Dielectric tensor: photon energies up to the width of the bands (eV).',
            'OPTICAL_EMAX = %s' % round(max(2.0, span), 1),
            '',
        ]
    if 'nonlinear' in props:
        lines += _nonlinear_constant_lines(cfg)
    if set(props) & ENERGY_WINDOW_PROPERTIES:
        lines.append(ENERGY_RANGE_BLOCK)
    lines += [
        '',
        'def new_paoflow():',
        '    """A PAOFLOW instance on the model (each run builds its own: nonlinear_optics needs the',
        '    real-space Hamiltonian that interpolated_hamiltonian replaces)."""',
        '    return PAOFLOW.PAOFLOW(',
        '        model=%s(**MODEL_PARAMETERS),' % function,
        '        workpath=HERE,',
        '        outputdir=OUTPUTDIR,',
        '        smearing=SMEARING,',
        '        npool=NPOOL,',
        '        verbose=False,',
        '    )',
        '',
    ]
    if standard:
        needs_spin = any(p in SPIN_PROPERTIES for p in props)
        lines += [
            '',
            'def run_properties():',
            '    """Bands, DOS, transport, Hall and topology on the model."""',
            '    p = new_paoflow()',
            '',
        ]
        lines += _emit_standard_properties(standard, needs_spin, cfg)
        lines += ['', '    p.finish_execution()', '']
    if 'optical' in props:
        lines += [
            '',
            'def run_optical():',
            '    """Dielectric tensor of the model (velocity from the hoppings and the orbital centres)."""',
            '    p = new_paoflow()',
            '    p.interpolated_hamiltonian(nfft1=NFFT[0], nfft2=NFFT[1], nfft3=NFFT[2])',
            '    p.pao_eigh()',
            '    p.gradient_and_momenta()',
            '    p.adaptive_smearing()',
            "    p.dielectric_tensor(emax=OPTICAL_EMAX, ne=801, d_tensor='diag', delta=0.1)",
            '    p.finish_execution()',
            '',
        ]
    if 'nonlinear' in props:
        lines += [
            '',
            'def run_nonlinear():',
            '    """Shift / injection currents and SHG from the real-space Hamiltonian of the model."""',
            '    p = new_paoflow()',
        ]
        lines += _nonlinear_call_lines(cfg)
        lines += ['', '    p.finish_execution()', '']
    lines += ['', 'def main():']
    calls = []
    if standard:
        calls.append('    run_properties()')
    if 'optical' in props:
        calls.append('    run_optical()')
    if 'nonlinear' in props:
        calls.append('    run_nonlinear()')
    lines += calls or ['    pass  # no properties selected']
    lines += [
        '',
        '',
        'if __name__ == "__main__":',
        '    # An error on one MPI rank stops every rank instead of hanging the job.',
        '    from PAOFLOW.utils.mpi_guard import run_main',
        '',
        '    run_main(main)',
        '',
    ]
    return '\n'.join(lines)
