"""``main.pyskeaf.py``: quantum oscillations (pyskeaf) from the Fermi-surface BXSF files.

The configuration comes from :data:`PAOFLOW.gen.questions.pyskeaf.PYSKEAF` (``paoflow-gen``,
workflow ``pyskeaf``, or the Setup tab of ``paoflow-studio``).
"""

from __future__ import annotations


def _literal(value) -> str:
    """Python text of a setting (tuples of the rotation as tuples, numbers as written)."""
    if isinstance(value, tuple):
        return '(%s)' % ', '.join(_literal(v) for v in value)
    if isinstance(value, list):
        return '[%s]' % ', '.join(_literal(v) for v in value)
    if isinstance(value, float):
        return repr(float(value))
    return repr(value)


def build_pyskeaf_script(cfg: dict) -> str:
    """Text of ``main.pyskeaf.py``.

    Parameters
    ----------
    cfg : dict
        :func:`PAOFLOW.gen.questions.pyskeaf.assemble_pyskeaf`.

    Returns
    -------
    str
        A driver that calls :meth:`PAOFLOW.PAOFLOW.PAOFLOW.pyskeaf` on the BXSF files of
        ``OUTPUTDIR`` (no QE save needed) and writes ``qo_EF_<energy>_freqvsangle_<band>.out``.
    """
    lines = [
        '#!/usr/bin/env python3',
        '"""Quantum oscillations with pyskeaf (generated by paoflow-gen).',
        '',
        'de Haas-van Alphen frequencies (extremal Fermi-surface orbits) against the direction of',
        'the magnetic field, from the single-band BXSF files Fermi_surf_band_<n>.bxsf that',
        'PAOFLOW.fermi_surface() writes (a Property run with the Fermi surface).  The results,',
        'qo_EF_<energy>_freqvsangle_<band>.out, go to the same folder; the Results tab of',
        'paoflow-studio plots them.  Run with:',
        '',
        '    python main.pyskeaf.py',
        '    mpirun -np <N> python main.pyskeaf.py      # the field directions spread over the ranks',
        '"""',
        '',
        'import os',
        '',
        'from PAOFLOW import PAOFLOW',
        '',
        '# ----------------------------------------------------------------------- #',
        '# Configuration  (edit freely)                                            #',
        '# ----------------------------------------------------------------------- #',
        'HERE = os.path.dirname(os.path.abspath(__file__))',
        'OUTPUTDIR = %r   # holds the Fermi_surf_band_*.bxsf files; the results go there'
        % cfg['outputdir'],
        "BANDS = %s   # 'all', or band numbers such as [5, 6]" % _literal(cfg['bands']),
        'FERMI_ENERGY = %s   # eV from E_F; a list scans energies, e.g. [-0.05, 0.0, 0.05]'
        % _literal(cfg['fermi_energy']),
        'NUM_INTERPOLATION = %d   # interpolated points per reciprocal-cell side'
        % cfg['num_interpolation'],
        '',
        '# Field direction: theta is its azimuth in the xy plane, phi its polar angle from +z',
        "# (degrees).  'rotation' goes from (THETA[0], PHI[0]) to (THETA[1], PHI[1]) in NUM_ANGLES",
        "# steps; 'non_principal' takes one (THETA, PHI); 'b1', 'b2', 'b3' follow a reciprocal vector.",
        'B_FIELD = %r' % cfg['b_field'],
        'THETA = %s' % _literal(cfg['azimuthal']),
        'PHI = %s' % _literal(cfg['polar']),
        'NUM_ANGLES = %d' % cfg['num_angles'],
        '',
        '# Extremal orbits.',
        'MINIMUM_FREQUENCY = %s   # kT' % _literal(float(cfg['minimum_frequency'])),
        'FREQUENCY_TOLERANCE = %s   # fractional frequency difference of orbits averaged together'
        % _literal(float(cfg['frequency_tolerance'])),
        'ORBIT_TOLERANCE = %s   # fractional distance (reciprocal cell) of orbits averaged together'
        % _literal(float(cfg['orbit_tolerance'])),
        'ALLOW_WALL_ORBITS = %r' % bool(cfg['allow_wall_orbits']),
        'VERBOSE = %r   # also the short, long and orbit-outline files' % bool(cfg['verbose']),
        '',
        '',
        'def main():',
        '    paoflow = PAOFLOW.PAOFLOW(workpath=HERE, outputdir=OUTPUTDIR, verbose=False)',
        '    paoflow.pyskeaf(',
        '        fermi_energy=FERMI_ENERGY,',
        '        num_interpolation=NUM_INTERPOLATION,',
        '        b_field=B_FIELD,',
        '        azimuthal=THETA,',
        '        polar=PHI,',
        '        num_angles=NUM_ANGLES,',
        '        minimum_frequency=MINIMUM_FREQUENCY,',
        '        frequency_tolerance=FREQUENCY_TOLERANCE,',
        '        orbit_tolerance=ORBIT_TOLERANCE,',
        '        allow_wall_orbits=ALLOW_WALL_ORBITS,',
        '        bands=BANDS,',
        '        verbose=VERBOSE,',
        '    )',
        '    paoflow.finish_execution()',
        '',
        '',
        'if __name__ == "__main__":',
        '    # An error on one MPI rank stops every rank instead of hanging the job.',
        '    from PAOFLOW.utils.mpi_guard import run_main',
        '',
        '    run_main(main)',
        '',
    ]
    return '\n'.join(lines)
